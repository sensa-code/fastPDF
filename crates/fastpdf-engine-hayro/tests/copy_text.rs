/// Writes the select-all copy text of the fixtures above and of the
/// synthetic documents to the file named by `$FASTPDF_COPY_SNAPSHOT`, to
/// compare copy text before and after a change.
#[test]
#[ignore = "measurement; run with --ignored --nocapture"]
fn copy_text_snapshot() {
    let Some(out) = std::env::var_os("FASTPDF_COPY_SNAPSHOT") else {
        return;
    };
    let mut report = String::new();
    let synthetic: [(&str, Vec<u8>); 5] = [
        ("synthetic/split-line", split_line_doc()),
        ("synthetic/two-column", two_column_doc()),
        ("synthetic/rotated-90", rotated_doc()),
        ("synthetic/spacing", spacing_doc()),
        ("synthetic/paragraphs", paragraphs_doc()),
    ];
    for (name, bytes) in synthetic {
        let text = copy_all(&layer(bytes, 0));
        report.push_str(&format!("===== {name}\n{text}\n"));
    }
    for (file, pages) in SNAPSHOT_FIXTURES {
        let Some(bytes) = fixture(file) else { continue };
        let doc = open_with(bytes, None, ResourceLimits::default()).unwrap();
        for &p in *pages {
            if p >= doc.page_count() {
                continue;
            }
            let layer = doc
                .text_layer(PageIndex::new(p), &CancelToken::new())
                .unwrap();
            report.push_str(&format!("===== {file}#{p}\n{}\n", copy_all(&layer)));
        }
    }
    std::fs::write(out, report).unwrap();
}
