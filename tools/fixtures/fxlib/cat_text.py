def _page_text_ops(lines: list[tuple[str, float, float, float, str]]) -> str:
    ops = []
    for font, size, x, y, text in lines:
        ops.append(f"BT /{font} {num(size)} Tf {num(x)} {num(y)} Td "
                   f"{pdf_lit(text.encode('cp1252', 'replace'))} Tj ET")
    return "\n".join(ops)


def pages_balanced_tree(out: Path, ctx: Ctx, pages: int = 2000, fan: int = 10) -> dict:
    """Balanced page tree with inherited MediaBox/CropBox/Rotate/Resources."""
    with open(out, "wb") as fp:
        pdf = RawPdf(fp, "1.7")
        f_helv = pdf.obj(std_font("Helvetica"))
        f_bold = pdf.obj(std_font("Helvetica-Bold"))
        f_times = pdf.obj(std_font("Times-Roman"))
        leaves = [pdf.alloc() for _ in range(pages)]
        levels = [leaves]
        while len(levels[-1]) > 1:
            prev = levels[-1]
            levels.append([pdf.alloc() for _ in range(math.ceil(len(prev) / fan))])
        parent: dict[int, Ref] = {}
        for li in range(len(levels) - 1):
            for i, ref in enumerate(levels[li]):
                parent[ref.num] = levels[li + 1][i // fan]
        # Inherited attribute overrides on selected intermediate nodes.
        overrides: dict[int, dict] = {
            levels[2][10].num: {"Rotate": 90},
            levels[2][15].num: {"MediaBox": [0, 0, 612, 792], "CropBox": [36, 36, 576, 756]},
            levels[1][0].num: {"Resources": {"Font": {"F1": f_times, "F2": f_bold}}},
        }

        def describe(i: int) -> str:
            n = i + 1
            if 1001 <= n <= 1100:
                return "inherits /Rotate 90 from a level-2 node"
            if 1501 <= n <= 1600:
                return "inherits Letter /MediaBox + /CropBox from a level-2 node"
            if n <= 10:
                return "inherits /Resources (Times-Roman as F1) from a level-1 node"
            return "inherits A4 /MediaBox and Helvetica /Resources from the root"

        for i, ref in enumerate(leaves):
            text = _page_text_ops([
                ("F2", 36, 60, 700, f"Page {i + 1} / {pages}"),
                ("F1", 12, 60, 660, describe(i)),
                ("F1", 10, 60, 640, "Page dictionary has no MediaBox/Resources of its own."),
            ])
            content = pdf.stream(text.encode("latin-1"))
            pdf.obj({"Type": "Page", "Parent": parent[ref.num], "Contents": content}, ref)
        for li in range(1, len(levels)):
            for i, ref in enumerate(levels[li]):
                kids = levels[li - 1][i * fan:(i + 1) * fan]
                count = min(pages, (i + 1) * fan ** li) - i * fan ** li
                d = {"Type": "Pages", "Kids": kids, "Count": count}
                if li < len(levels) - 1:
                    d["Parent"] = parent[ref.num]
                else:
                    d["MediaBox"] = [0, 0, 595.2756, 841.8898]
                    d["Resources"] = {"Font": {"F1": f_helv, "F2": f_bold},
                                      "ProcSet": ["PDF", "Text"]}
                d.update(overrides.get(ref.num, {}))
                pdf.obj(d, ref)
        root = pdf.obj({"Type": "Catalog", "Pages": levels[-1][0], "PageLayout": "SinglePage"})
        info = pdf.obj(info_dict(f"FastPDF fixture: {pages} pages, balanced page tree"))
        pdf.finish(root, info, id_seed="pages-balanced-tree")
    return {"pages": pages}


def pages_objstm(out: Path, ctx: Ctx, pages: int = 2000, fan: int = 50) -> dict:
    """PDF 1.5 file: page dicts in object streams, cross-reference stream."""
    sizes = [(595.2756, 841.8898), (612, 792), (419.5276, 595.2756), (1190.5512, 841.8898)]
    with open(out, "wb") as fp:
        pdf = RawPdf(fp, "1.5", objstm_size=100)
        f1 = pdf.objstm_obj(std_font("Helvetica"))
        f2 = pdf.objstm_obj(std_font("Courier-Bold"))
        root_pages = pdf.alloc()
        groups = [pdf.alloc() for _ in range(math.ceil(pages / fan))]
        for gi, gref in enumerate(groups):
            kids = []
            for i in range(gi * fan, min(pages, (gi + 1) * fan)):
                w, h = sizes[i % len(sizes)]
                text = _page_text_ops([
                    ("F2", 28, 40, h - 80, f"Page {i + 1} / {pages}"),
                    ("F1", 11, 40, h - 110, f"Object-stream page, size {num(w)} x {num(h)} pt"),
                ])
                content = pdf.stream(text.encode("latin-1"))
                kids.append(pdf.objstm_obj({"Type": "Page", "Parent": gref,
                                            "MediaBox": [0, 0, w, h], "Contents": content}))
            pdf.objstm_obj({"Type": "Pages", "Parent": root_pages, "Kids": kids,
                            "Count": len(kids)}, gref)
        pdf.objstm_obj({"Type": "Pages", "Kids": groups, "Count": pages,
                        "Resources": {"Font": {"F1": f1, "F2": f2}}}, root_pages)
        root = pdf.objstm_obj({"Type": "Catalog", "Pages": root_pages})
        info = pdf.objstm_obj(info_dict(f"FastPDF fixture: {pages} pages in object streams"))
        pdf.finish(root, info, id_seed="pages-objstm", xref_stream=True)
    return {"pages": pages}


