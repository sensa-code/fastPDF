def small_three_pages_platypus(out: Path, ctx: Ctx) -> dict:
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib import colors
    from reportlab.platypus import (PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table,
                                    TableStyle, ListFlowable, ListItem)

    r = rng("small-three-pages")
    ss = getSampleStyleSheet()
    body = ss["BodyText"]
    body.fontName = "Times-Roman"
    body.fontSize = 11
    body.leading = 14

    def on_page(canvas, doc):
        n = canvas.getPageNumber()
        canvas.bookmarkPage(f"p{n}")
        canvas.addOutlineEntry(f"Page {n}", f"p{n}", level=0)
        canvas.setFont("Times-Italic", 8)
        canvas.drawString(72, 40, f"{LOREM_NOTE}  Page {n}")

    story = [Paragraph('<a name="intro"/>FastPDF fixture: three pages (platypus)', ss["Title"])]
    for _ in range(5):
        story.append(Paragraph(latin_paragraph(r, 4, 6), body))
    story.append(ListFlowable([ListItem(Paragraph(latin_sentence(r), body)) for _ in range(5)],
                              bulletType="bullet"))
    story.append(PageBreak())
    story.append(Paragraph("Section 2: a simple table", ss["Heading2"]))
    data = [["Metric", "Value", "Unit"]] + [
        [f"metric_{i:02d}", f"{r.uniform(0, 1000):.2f}", r.choice(["ms", "MB", "pages", "%"])]
        for i in range(14)]
    t = Table(data, colWidths=[160, 100, 80])
    t.setStyle(TableStyle([("FONT", (0, 0), (-1, -1), "Helvetica", 9),
                           ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 9),
                           ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                           ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
                           ("ALIGN", (1, 1), (1, -1), "RIGHT")]))
    story += [t, Spacer(1, 12)]
    for _ in range(3):
        story.append(Paragraph(latin_paragraph(r, 3, 5), body))
    story.append(PageBreak())
    story.append(Paragraph("Section 3: links", ss["Heading2"]))
    story.append(Paragraph('Internal link back to <a href="#intro" color="blue">the title</a>; '
                           'external link to <a href="https://example.com/fastpdf" color="blue">'
                           'example.com</a>.', body))
    for _ in range(4):
        story.append(Paragraph(latin_paragraph(r, 3, 5), body))

    doc = SimpleDocTemplate(str(out), pagesize=letter, title="FastPDF fixture: three pages",
                            author="FastPDF fixture generator (synthetic content)",
                            invariant=1)
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return {"pages": doc.page}


