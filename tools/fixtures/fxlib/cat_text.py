class _Words:
    """Endless stream of synthetic words, consumed one justified-width line at a time."""

    def __init__(self, r):
        self.r = r
        self.buf: list[str] = []
        self.pending: str | None = None

    def _next(self) -> str:
        if self.pending is not None:
            w, self.pending = self.pending, None
            return w
        if not self.buf:
            self.buf = latin_sentence(self.r).split()[::-1]
        return self.buf.pop()

    def line(self, wfn, space: float, max_w: float) -> str:
        cur: list[str] = []
        cur_w = 0.0
        while True:
            w = self._next()
            ww = wfn(w)
            if cur and cur_w + space + ww > max_w:
                self.pending = w
                return " ".join(cur)
            cur_w += (space if cur else 0.0) + ww
            cur.append(w)


def large_dense_times(out: Path, ctx: Ctx, pages: int = 300) -> dict:
    r = rng("large-dense-times")
    c = rl_canvas(out, f"FastPDF fixture: {pages} pages dense Times-Roman")
    W, H = A4
    font, size, leading = "Times-Roman", 9.0, 10.6
    wfn = width_fn(font, size)
    space = wfn(" ")
    words = _Words(r)
    max_w = W - 100
    for p in range(1, pages + 1):
        if (p - 1) % 10 == 0:
            ch = (p - 1) // 10 + 1
            c.bookmarkPage(f"ch{ch}")
            c.addOutlineEntry(f"Chapter {ch}", f"ch{ch}", level=0)
        c.setFont("Times-Bold", 11)
        c.drawString(50, H - 40, f"Chapter {(p - 1) // 10 + 1} - dense text page {p}")
        t = c.beginText(50, H - 58)
        t.setFont(font, size, leading)
        y = H - 58
        while y > 50:
            t.textLine(words.line(wfn, space, max_w))
            y -= leading
        c.drawText(t)
        c.setFont("Times-Italic", 7)
        c.drawCentredString(W / 2, 30, f"- {p} -")
        c.showPage()
    c.save()
    return {"pages": pages}


